/* =====================================================================
   بإيدك: إعدادات سلوك الـESP32 اللي في صفحة «المعمل» (lab.html)
   ---------------------------------------------------------------------
   الملف ده لصاحب الموقع. عدّلوا القيم اللي هنا براحتكم، واحفظوا الملف،
   وافتحوا الصفحة تاني: الـESP والسيريال مونيتور بيقروا كل حاجة من هنا،
   ومفيش أي كود تاني محتاج يتغير.

   قواعد بسيطة علشان الملف ما يبوظش:
   - النص العربي بيتكتب بين علامتين ' ' أو " ".
   - بعد كل سطر فيه قيمة فيه فاصلة , (إلا آخر سطر جوه القوس).
   - الألوان بصيغة #RRGGBB (مثلًا '#3DF58C').
   - الوقت دايمًا بالمللي ثانية (1000 = ثانية واحدة).
   - لو حصل خطأ في الملف، المعمل بيشتغل بالقيم الافتراضية اللي جوه lab.js،
     وبيظهر سطر أحمر في السيريال مونيتور يقول كده.

   الملف ده بيتحكم في الـESP32 الوهمي بس. جهاز الزائر الحقيقي (لو وصّله بالـUSB)
   بينفّذ كود الجسر assets/firmware/beedak-lab-bridge/beedak-lab-bridge.ino، وبيوصله
   من كود الزائر: led و blink و delay و say و color بس (wifi و rotate للمعمل بس).
   الـsequences اللي هنا لو اتشغلت بـ run(...) بتتبعت للجهاز بنفس القاعدة.
   ===================================================================== */
window.ESP_BEHAVIOR = {

  /* الاسم اللي بيظهر في السيريال وعلى زرار اختيار الجهاز */
  name: 'ESP32',

  /* ---------- اللمبة (LED) اللي على الكارت ---------- */
  led: {
    // الألوان المتاحة بالاسم. الاسم ده هو اللي الزوار بيكتبوه في color(...)
    colors: { green: '#3DF58C', red: '#FF4D5E', violet: '#A78BFA' },
    // اللون اللي اللمبة بتبدأ بيه (لازم يكون اسم من اللي فوق)
    startColor: 'green',
    // اللمبة شغالة من الأول ولا لأ (true = شغالة، false = مطفية)
    startOn: false,
    // وقت كل نَفَس في التغميز (اللمبة بتنوّر المدة دي وتطفى المدة دي)
    // أقل قيمة مسموحة 200 (علشان مفيش وميض أسرع من 3 مرات في الثانية)
    blinkMs: 450
  },

  /* ---------- الواي فاي ---------- */
  wifi: {
    // اسم الشبكة اللي بيظهر في السيريال (شبكة وهمية للعب)
    ssid: 'beedak-lab',
    // الحالة اللي بيبدأ بيها: 'disconnected' أو 'connected'
    startState: 'disconnected',
    // الوقت اللي بياخده لحد ما يتصل
    connectMs: 1600,
    // لون كل حالة: مقطوع أحمر، بيحاول بنفسجي، متصل أخضر
    colors: { disconnected: '#FF4D5E', connecting: '#A78BFA', connected: '#3DF58C' },
    // الكلمة اللي بتظهر فوق السيريال مونيتور في كل حالة
    labels: { disconnected: 'WL_DISCONNECTED', connecting: 'WL_IDLE…', connected: 'WL_CONNECTED' }
  },

  /* ---------- رسايل السيريال مونيتور ---------- */
  serial: {
    // السرعة اللي مكتوبة فوق الشاشة (شكل بس)
    baud: 115200,
    // أقصى عدد سطور بيتعرض (القديم بيتشال)
    maxLines: 60,
    // السطور اللي بتظهر أول ما الـESP يقوم
    bootLines: ['rst:0x1 (POWERON_RESET)', 'boot: ESP32 جاهز'],
    // رسايل الأحداث. {ssid} بيتبدل باسم الشبكة، و{color} باسم اللون
    messages: {
      connecting: 'بيحاول يتصل بـ {ssid}…',
      connected: 'اتصل بـ {ssid}',
      disconnected: 'الواي فاي اتقطع',
      ledOn: 'اللمبة نوّرت',
      ledOff: 'اللمبة طفت',
      color: 'لون اللمبة بقى {color}',
      done: 'خلص.'
    }
  },

  /* ---------- الدوسة على الـESP (بالماوس أو بالصباع أو Enter) ----------
     اكتبوا اسم sequence من اللي تحت، أو '' علشان ما يحصلش حاجة */
  onClick: 'hello',

  /* أول ما الزائر يوصل للمعمل بيشتغل الـsequence ده مرة واحدة ('' = ولا حاجة) */
  autoRun: 'boot',

  /* ---------- الحركة ---------- */
  idle: {
    // الـESP يلف لوحده بالراحة لحد ما الزائر يلمس أي جهاز
    // (بيقف لوحده مع زرار «وقّفوا الحركة» أو إعداد تقليل الحركة في الجهاز)
    spin: true,
    // سرعة اللفة دي: درجة في الثانية
    spinSpeed: 10
  },
  rotation: {
    // قد إيه الجهاز بيلف مع كل بيكسل سحب
    dragSpeed: 0.6,
    // يكمّل يلف شوية بعد ما تسيبوه (بيتلغي لوحده مع تقليل الحركة)
    inertia: true,
    // كل ضغطة سهم في الكيبورد بتلف كام درجة
    keyStep: 15
  },

  /* مكان البداية على الترابيزة:
     x من -0.5 (أقصى الشمال) لـ 0.5 (أقصى اليمين)، و y من -0.5 (ورا) لـ 0.5 (قدام)
     yaw = اللفة حوالين نفسه، و pitch = الميلة لقدام أو لورا (بالدرجات) */
  start: { x: -0.27, y: 0.14, yaw: -28, pitch: 0 },

  /* ---------- الـsequences: خطوات بتتنفذ ورا بعض ----------
     كل خطوة واحدة من دول (و ms معناها استنى المدة دي بعد الخطوة):
       { led: 'on' } أو { led: 'off' } أو { led: 'toggle' }
       { color: 'green' }            لون من led.colors
       { blink: 3 }                  يغمّز 3 مرات (بسرعة led.blinkMs)
       { wifi: 'connect' } أو { wifi: 'disconnect' }
       { say: 'أي نص' }              يكتب سطر في السيريال
       { rotate: 90 }                يلف الجهاز 90 درجة
       { wait: 500 }                 يستنى نص ثانية
       { run: 'اسم sequence تاني' }
     الزوار يقدروا يشغّلوا أي sequence من هنا بكتابة run(اسمه) في محرر الكود. */
  sequences: {
    boot: [
      { led: 'off' },
      { say: 'setup()…', ms: 300 },
      { wifi: 'connect' },
      { color: 'green' },
      { blink: 2 }
    ],
    hello: [
      { say: 'أهلًا! أنا الـESP32 اللي في المعمل.' },
      { color: 'violet' },
      { blink: 2 },
      { rotate: 180, ms: 200 },
      { color: 'green' },
      { led: 'on' }
    ],
    alarm: [
      { say: 'فيه عطل: الحساس مش بيرد' },
      { color: 'red' },
      { blink: 3 },
      { wifi: 'disconnect', ms: 600 },
      { say: 'لقينا السبب، بنصلّح…', ms: 400 },
      { wifi: 'connect' },
      { color: 'green' },
      { led: 'on' }
    ]
  }
};
